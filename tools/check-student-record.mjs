import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const portal=await fs.readFile(new URL('shared/js/portal.js',root),'utf8');
const source=await fs.readFile(new URL('shared/js/workspace-cycle.js',root),'utf8');
const element=()=>({setAttribute(){},append(){},addEventListener(){},classList:{add(){}},style:{}});
const sandbox={window:{},document:{addEventListener(){},createElement:element,getElementById(){return null;}},location:{pathname:'/pages/platform-admin/platform-admin.html'},sessionStorage:{getItem(){return null;}},console,Date,crypto:globalThis.crypto};
vm.createContext(sandbox);
vm.runInContext(portal.slice(portal.indexOf('window.BridgewayPartners ='),portal.indexOf('// URL context')),sandbox);
for(const file of ['report-visibility','workspace-cycle','partnership-review'])vm.runInContext(await fs.readFile(new URL(`shared/js/${file}.js`,root),'utf8'),sandbox);
const C=sandbox.window.BridgewayCycle,P=sandbox.window.BridgewayPartnerships;
const before=JSON.stringify(C.state.histories),alice=C.placementRecord('alice');
assert.equal(alice.current.id,'placement-alice');
assert.equal(alice.current.status,'Active');
assert.equal(alice.activeCount,1,'Alice has only one active internship');
assert.equal(alice.previous.length,1);
assert.equal(alice.previous[0].id,'placement-alice-old');
assert.equal(alice.previous[0].status,'Left');
assert.equal(alice.previous[0].end,'2026-07-15');
assert.equal(P.placementHours(alice.current),120);
assert.equal(P.placementHours(alice.previous[0]),80,'Historical hours stay separate');
assert.equal(C.placementRecord('ghaith').previous.length,0);
assert.equal(C.placementRecord('sarah').current.status,'Completed');
assert.equal(C.placementRecord('omar').current,null);
assert.equal(JSON.stringify(C.state.histories),before,'Viewing a record must not rewrite history');
assert(source.includes("E('details',null,'record-history')"),'Previous placements use a closed-by-default native disclosure');
assert(source.includes("record.trainingOwner===h.id"),'Current plan and evaluation actions stay bound to their own placement');
assert(!source.includes('verified hours in the current training record.'),'Do not repeat current hours beneath historical records');
console.log('PASS: One active Alice placement, clearly separate ended history and hours, no-placement/completed states, closed history disclosure and placement-specific actions.');
