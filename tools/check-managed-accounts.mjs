import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {webcrypto as crypto} from 'node:crypto';
const source=fs.readFileSync(new URL('../shared/js/managed-account-editor.js',import.meta.url),'utf8');
const stored=[{id:'student-1',type:'student',college:'college-1',name:'Test student',email:'student@example.test',studentId:'20260001'},{id:'supervisor-1',type:'supervisor',college:'college-1',name:'Test supervisor',email:'supervisor@example.test',staffId:'STAFF-1'}];
const window={BridgewayPartners:{organizations:[{id:'company-1',email:'company@example.test'}]}};
vm.runInNewContext(source,{window,crypto,sessionStorage:{getItem:()=>JSON.stringify(stored)},document:{addEventListener(){}}});
const validate=window.BridgewayAccountEditor.validate;
assert(validate({type:'student',college:'college-1',studentId:'OTHER',email:'STUDENT@example.test'},'new').includes('email'));
assert(validate({type:'student',college:'college-1',studentId:'20260001',email:'new@example.test'},'new').includes('student ID'));
assert(validate({type:'supervisor',college:'college-1',staffId:'STAFF-1',email:'new@example.test'},'new').includes('staff ID'));
assert(validate({type:'college',email:'company@example.test'},'new').includes('email'));
assert.equal(validate({...stored[0]},'student-1'),'','Editing own account must not count as a duplicate');
const editor=window.BridgewayAccountEditor;
const createFields=editor.schema('supervisor').flatMap(group=>group.fields).map(field=>field.name);
for(const removed of ['staffId','office','officeHours','status'])assert(!createFields.includes(removed),removed+' must not be requested during creation');
for(const kept of ['name','email','phone','faculty','department','title'])assert(createFields.includes(kept),kept+' must remain');
for(const type of ['student','company','college'])assert(!editor.schema(type).flatMap(group=>group.fields).some(field=>field.name==='status'));
assert.equal(editor.accountDefaults('student').status,'Active');
const assigned=editor.accountDefaults('supervisor');assert(assigned.staffId.startsWith('SUP-'));
assert.notEqual(assigned.staffId,editor.accountDefaults('supervisor').staffId);
assert.equal(editor.accountDefaults('supervisor',{staffId:assigned.staffId,status:'Suspended'}).staffId,assigned.staffId);
assert.equal(editor.accountDefaults('supervisor',{status:'Suspended'}).status,'Suspended');
for(const type of ['student','supervisor','company','college'])assert(source.includes(`${type}:`),type);
assert(source.includes("if(!['password','confirmPassword'].includes(name))"),'Passwords must never be serialized');
assert(source.includes("input.minLength=12"));assert(source.includes("Passwords must match."));
assert(source.includes('confirmAction'),'Account changes require confirmation');
assert(source.includes("toggle.setAttribute('aria-controls',input.id)"),'Password visibility buttons must identify their input');
assert(source.includes("querySelectorAll('[data-credential]')"),'Shown and hidden passwords must both be cleared on close');
for(const type of ['student','supervisor','company','college']){
  const fields=editor.schema(type).flatMap(group=>group.fields).map(field=>field.name);
  for(const removed of ['staffId','office','officeHours','status'])assert(!fields.includes(removed),type+': '+removed);
}
assert(!source.includes("stage='Placed'"),'Account creation must not activate training');
const college=fs.readFileSync(new URL('../pages/admin-dashboard/admin-dashboard.html',import.meta.url),'utf8');
const platform=fs.readFileSync(new URL('../pages/platform-admin/platform-admin.html',import.meta.url),'utf8');
assert(college.includes('managed-account-editor.js')&&platform.includes('managed-account-editor.js'));
assert(!college.includes('value="password123"'));
console.log('PASS: All administrator-created account roles, duplicate email/IDs, edit handling, confirmations, password exclusion and no automatic placement.');
