import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../shared/js/portal.js',import.meta.url),'utf8');
const start=source.indexOf('    window.removeCollegeStudentRecord=row=>{');
const end=source.indexOf('\n    };',start)+7;
assert(start>0&&end>start);
let refreshes=0,undo,persisted;
const body={insertBefore(row,next){row.parentElement=this;row.restoredBefore=next;}};
const sibling={parentElement:body};
const row={parentElement:body,nextSibling:sibling,remove(){this.parentElement=null;}};
const context={window:{BridgewayKinetic:{undoToast(text,fn){assert(text.includes('college directory'));undo=fn;}}},studentsBody:body,studentKey:()=> 'omar',counts:()=>refreshes++,removed:[],saveRemoved:()=>{persisted=[...context.removed];}};
vm.runInNewContext(source.slice(start,end),context);
context.window.removeCollegeStudentRecord(row);
assert.equal(row.parentElement,null);
assert.deepEqual(persisted,['omar']);
assert.equal(refreshes,1);
undo();
assert.equal(row.parentElement,body);
assert.equal(row.restoredBefore,sibling);
assert.deepEqual(persisted,[]);
assert.equal(refreshes,2);
context.window.removeCollegeStudentRecord({parentElement:{}});
assert.equal(refreshes,2,'Only this college directory is in scope');
assert(source.includes("appendManagedStudent('Omar Majed'"));
assert(source.includes("appendManagedStudent('Lina Haddad'"));
assert(!source.includes("'After company acceptance','Application pending'"));
console.log('PASS: Student directory removal, retained model boundaries, Undo, counts, persistence tracking, and controls for pending/unapplied students.');
