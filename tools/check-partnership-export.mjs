const blob=sandbox.window.BridgewayWorkbook.build(process.argv.includes('--details')?details:sheets);
const bytes=new Uint8Array(await blob.arrayBuffer());
assert.equal(new DataView(bytes.buffer).getUint32(0,true),0x04034b50);
const text=new TextDecoder().decode(bytes);
assert(!text.includes('<f>'),'Exports must never execute user-supplied text as formulas');
assert(text.includes('=NOT_A_FORMULA()'));
assert(text.includes('state="frozen"'));
assert(text.includes('<autoFilter'));
assert(text.includes('showGridLines="0"'));
assert(text.includes('formatCode="dd mmm yyyy"'));
assert(text.includes('<conditionalFormatting'),'Statuses use native conditional formatting');
const differentialStyles=text.match(/<dxfs[^>]*>([\s\S]*?)<\/dxfs>/)?.[1];
assert(differentialStyles,'Conditional formats must define their colors');
assert(!differentialStyles.includes('indexed="64"'),'Status fills must not use an automatic/system background that Excel can display as black');
assert(differentialStyles.includes('<fgColor rgb="FFE7F5EF"/><bgColor rgb="FFE7F5EF"/>'),'Status fills explicitly agree in both foreground and background');
assert(text.includes('applyFill="1"'),'Body banding must be explicit');
assert(text.includes('<tableParts')&&text.includes('TableStyleLight9'),'Native Excel tables provide sortable/filterable records');
assert(text.includes('formatCode="#,##0.00"'),'Fractional hours remain visible');
assert(text.includes('zoomScale="90"'),'Exports open at a readable scale');
const fractionalBlob=sandbox.window.BridgewayWorkbook.build([{name:'Format check',headers:['ID','Hours','Date','Status'],rows:[['0012',37.5,new Date('2026-10-17T00:00:00Z'),'Open'],['0013',0,null,'Resolved']]}]);
const fractionalXml=new TextDecoder().decode(new Uint8Array(await fractionalBlob.arrayBuffer()));
assert(fractionalXml.includes('<c r="B6" s="11"><v>37.5</v></c>'),'Fractional hours use a decimal style without changing the numeric value');
assert(fractionalXml.includes('<c r="B7" s="5"><v>0</v></c>'),'Zero stays numeric and uses the integer style');
assert(text.includes('<row r="5" ht="48"'),'Headers reserve space for wrapping and filter buttons');
assert(text.includes('Active\ninterns'),'Summary headings use short, clear labels');
assert(text.includes('orientation="landscape"'));
assert(text.includes('_xlnm.Print_Titles'));
assert(text.includes('topLeftCell="A6"'),'Overview freezes only the header rows');
assert(text.includes('dxfId="4"')&&text.includes('dxfId="5"'),'Overview statuses use text emphasis instead of filled column blocks');
assert.throws(()=>sandbox.window.BridgewayWorkbook.build([{name:'Bad/Name',headers:['A'],rows:[]}]),/Invalid worksheet name/);
assert.throws(()=>sandbox.window.BridgewayWorkbook.build([{name:'Test',headers:['A'],rows:[[1,2]]}]),/Invalid worksheet columns/);
assert.throws(()=>sandbox.window.BridgewayWorkbook.build([{name:'Test',headers:['A'],headerLabels:['A','B'],rows:[]}]),/Invalid worksheet columns/);
if(process.argv[2])await fs.writeFile(process.argv[2],bytes);
console.log('PASS: Compact workbook, optional detail, retained history, filters, placement isolation, typed dates, print layout, native status formatting and formula-safe text.');
