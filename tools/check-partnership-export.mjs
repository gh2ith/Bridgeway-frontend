assert.equal(all.summary.reduce((n,r)=>n+r.histories.length,0),4);
assert.equal(P.collect({college:'college-2',company:'company-2'}).summary[0].left,1);
assert.equal(P.collect({college:'college-1',company:'company-1'}).summary[0].students,1);
