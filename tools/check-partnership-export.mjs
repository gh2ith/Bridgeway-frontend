old.verifiedHours=80;
const week=C.state.plans.ghaith[5];week.attendance={scheduled:40,attended:32,excused:0,unexcused:8,late:1,evidence:'Sample dates and timesheet',by:'Tech Corp Inc.',at:'2026-10-15T12:00:00Z'};
C.state.tickets.push({id:'test-ticket',owner:'company:company-1',reference:'report:ghaith:5',placement:'placement-ghaith',subject:'Sample attendance concern',status:'Open',priority:'Normal',created:'2026-10-15T12:00:00Z',messages:[{author:'Company',at:'2026-10-15T12:00:00Z',body:'=NOT_A_FORMULA()'}]});
let filtered=P.collect({college:'college-1',company:'company-1'});
assert.equal(filtered.summary[0].absent,8);
assert.equal(filtered.summary[0].late,1);
assert.equal(filtered.tickets.length,1);
assert.equal(P.collect({college:'college-2'}).tickets.length,0);
assert.equal(P.collect({from:'2026-10-01'}).tickets.length,0);
const sheets=P.sheets(filtered);
assert.equal(sheets.length,4);
assert.deepEqual(Array.from(sheets,s=>s.name),['Partnerships','Placements','Weekly reports','Tickets']);
assert(sheets.every(s=>s.headers.length<=11),'Default sheets stay narrow');
assert.equal(sheets[0].rows[0][3],1);
assert.equal(sheets[0].headers.length,6,'The first sheet is a compact overview, not a repeated detail table');
assert.deepEqual(Array.from(sheets[0].headers),['College','Company','Status','Students','Active interns','Verified hours']);
const summarySheet=P.sheets(P.collect())[0];
assert(summarySheet.rows.every(row=>['Active','Inactive'].includes(row[2])),'Exported partnership status is strictly binary');
assert.equal(summarySheet.rows.find(row=>row[0]==='Jordan University'&&row[1]==='Nexus Cloud Systems')[2],'Inactive','Past relationships are inactive without removing their training history');
assert.equal(summarySheet.rows.find(row=>row[0]==='Jordan University'&&row[1]==='Nexus Cloud Systems')[5],80,'Inactive relationships retain historical hours');
assert.equal(summarySheet.freezeColumns,0,'Do not split the compact overview with a vertical freeze divider');
const liveLink=sandbox.window.BridgewayPartners.links.find(l=>l.college==='college-1'&&l.company==='company-1');
const priorLinkStatus=liveLink.status;liveLink.status='Paused';
