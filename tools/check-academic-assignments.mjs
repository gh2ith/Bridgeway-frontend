import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../shared/js/portal.js',import.meta.url),'utf8');
const block=source.slice(source.indexOf('// Academic assignment is independent'),source.indexOf('// URL context selects'));
const storage=new Map();
const students=[{id:'omar',name:'Omar',college:'college-1',supervisor:null,stage:'Applied'},{id:'lina',name:'Lina',college:'college-1',supervisor:null,stage:'Not applied'},{id:'other',name:'Other',college:'college-2',supervisor:'Other supervisor',stage:'Placed'}];
const application={student:'omar',status:'Pending'};
const window={BridgewayPartners:{students},BridgewayCycle:{state:{applications:[application]},commit(){}}};
const sessionStorage={getItem:key=>storage.get(key),setItem:(key,value)=>storage.set(key,value)};
vm.runInNewContext(block,{window,sessionStorage});
assert.equal(window.BridgewayAcademicAssignments.set('Omar','college-1','Dr. Ahmad S.'),true);
assert.equal(window.BridgewayAcademicAssignments.set('Lina','college-1','Dr. Ahmad S.'),true);
assert.equal(students[0].supervisor,'Dr. Ahmad S.');assert.equal(students[1].supervisor,'Dr. Ahmad S.');
assert.equal(students[0].stage,'Applied');assert.equal(students[1].stage,'Not applied');
assert.deepEqual(application,{student:'omar',status:'Pending'},'Assignment must not accept an application or activate training');
assert.equal(window.BridgewayAcademicAssignments.set('Other','college-1','Dr. Ahmad S.'),false,'No cross-college assignment');
students[0].supervisor=null;vm.runInNewContext(block,{window,sessionStorage});
assert.equal(students[0].supervisor,'Dr. Ahmad S.','Assignment survives reload in the browser session');
window.BridgewayAcademicAssignments.set('Omar','college-1','');
vm.runInNewContext(block,{window,sessionStorage});assert.equal(students[0].supervisor,null,'Unassignment also survives reload');
console.log('PASS: Academic assignment before applications/acceptance, unassignment, college boundaries, session reload, and unchanged hiring/placement status.');
