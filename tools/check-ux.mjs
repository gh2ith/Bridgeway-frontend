// Dependency-free checks for page-only edit tracking. No browser storage is provided.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const scope={window:{addEventListener(){}},document:{addEventListener(){}},Map,Set};
vm.runInNewContext(fs.readFileSync(new URL('../shared/js/portal-ux.js',import.meta.url),'utf8'),scope);
const ux=scope.window.BridgewayUX;
const text={type:'text',value:'',readOnly:false,disabled:false};
const week={type:'select-one',value:'4',readOnly:false,disabled:false};
const password={type:'password',value:'',readOnly:false,disabled:false};
password.dataset={credential:'true'};
const readonly={type:'text',value:'University',readOnly:true};
let rating='';
const root={querySelectorAll(selector){return selector==='input,textarea,select'?[text,week,password,readonly]:[{querySelector(){return rating?{dataset:{val:rating}}:null;}}];},toggleAttribute(){}};
ux.remember(root);assert.equal(ux.dirty(root),false);
text.value='Work in progress';assert.equal(ux.dirty(root),true);
ux.remember(root);assert.equal(ux.dirty(root),false);
week.value='5';assert.equal(ux.dirty(root),true);assert.equal(ux.dirty(root,week),false);
week.value='4';rating='4';assert.equal(ux.dirty(root),true);
rating='';readonly.value='Different university';assert.equal(ux.dirty(root),false);
password.value='sample-only';assert.equal(typeof ux.capture(root).values.get(password),'number');assert.equal(ux.dirty(root),true);
password.value='';text.value='';assert.equal(ux.dirty(root),true);
ux.remember(root);assert.equal(ux.dirty(root),false);
console.log('PASS: Edit tracking, baseline reset, week-change exclusions, rating changes, and no stored password text.');
password.type='text';assert.equal(ux.dirty(root),false,'Showing a credential must not create an unsaved edit');
assert.equal(typeof ux.capture(root).values.get(password),'number','Visible credentials must still be captured only as lengths');
root.dataset={committed:'true'};text.value='Submitted ticket';
assert.equal(ux.dirty(root),false,'A successfully submitted form must not warn about unsaved changes');
root.dataset.committed='false';assert.equal(ux.dirty(root),true,'Unsubmitted edits must remain protected');
