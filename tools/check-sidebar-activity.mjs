import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const window={};vm.runInNewContext(fs.readFileSync(new URL('../shared/js/sidebar-activity.js',import.meta.url),'utf8'),{window,document:{addEventListener(){}}});
const {sources,unread}=window.BridgewaySidebarActivity;
let viewer='supervisor:ahmad';
const model={students:[{id:'one',company:'company-1',college:'college-1',supervisor:'Dr. Ahmad S.'}]};
const ticket={id:'new',owner:'student:one',status:'In progress',messages:[{sender:'student:one',at:'1',author:'Student'}]};
const state={tickets:[ticket],plans:{one:[]},applications:[],listings:[]};
const C={state,identity:()=>viewer,ticketVisible:t=>viewer==='supervisor:ahmad'||t.owner===viewer};
let records=sources(C,'supervisor',model)['tab-tickets'];
assert(unread(records),'An unseen received ticket raises activity');
const seen=Object.fromEntries(records);assert(!unread(records,seen),'Viewing the section clears activity');
assert(!unread(sources(C,'supervisor',model)['tab-tickets'],seen),'An existing ticket does not reappear as new');
ticket.messages.push({sender:'student:one',author:'Student',at:'2'});
assert(unread(sources(C,'supervisor',model)['tab-tickets'],seen),'A new reply brings activity back');
ticket.messages.push({sender:viewer,author:'Supervisor',at:'3'});
assert(!unread(sources(C,'supervisor',model)['tab-tickets'],seen),'The viewer’s own reply is not new activity');
viewer='student:one';assert(unread(sources(C,'student',model)['tab-tickets']),'The supervisor reply is unseen to its requester');
viewer='company:company-1';state.tickets=[];
state.applications.push({id:'a',student:'one',company:'company-1',status:'Pending',at:'4'});
const company=sources(C,'company',model);assert(unread(company['tab-candidates']));
assert(!('tab-accepted-students' in company),'Intern totals do not produce activity');
const readApps=Object.fromEntries(company['tab-candidates']);assert(!unread(company['tab-candidates'],readApps));
state.applications.push({id:'b',company:'company-1',status:'Pending',at:'5'});assert(unread(sources(C,'company',model)['tab-candidates'],readApps));
assert(!('tab-roster' in sources(C,'supervisor',model)),'Assigned-student totals do not produce activity');
console.log('PASS: Unseen tickets and replies, clear-on-view, fresh activity after viewing, own-reply exclusion, role scope, and application activity without roster totals.');
